  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  slug TEXT UNIQUE NOT NULL,
  title TEXT NOT NULL,
  category TEXT NOT NULL DEFAULT 'Initiative',
  description TEXT,
  url TEXT NOT NULL,
  img TEXT,
  icon TEXT,
  alt TEXT,
  rank_score INTEGER NOT NULL DEFAULT 100 CHECK (rank_score >= 0),
